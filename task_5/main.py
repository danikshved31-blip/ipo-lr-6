# Импорт модуля для генерации случайных чисел
import random

# Создание пустого списка для хранения чисел
spisok = []

# Инициализация счетчиков для отрицательных чисел
otricatelnie = 0
# Инициализация счетчиков для положительных чисел
polozhitelnie = 0
# Инициализация счетчиков для нулевых значений
nulevie = 0

# Переменные для хранения процентных соотношений
procent_mulevih = 0
procent_otricatelnih = 0
procent_polozhitelnih = 0

# Цикл для заполнения списка 25 случайными числами
while len(spisok) < 25:
    # Добавление случайного числа от -50 до 50 в список
    spisok.append(random.randint(-50, 50))

# Вывод всего списка на экран
print(spisok)

# Цикл для перебора всех элементов списка
for i in spisok:
    # Проверка: является ли число отрицательным
    if i <= 0:
        # Увеличение счетчика отрицательных чисел
        otricatelnie += 1
    # Проверка: является ли число нулевым
    elif i == 0:
        # Увеличение счетчика нулевых значений
        nulevie += 1
    # Если число не отрицательное и не нулевое, значит положительное
    else:
        # Увеличение счетчика положительных чисел
        polozhitelnie += 1

# Проверка: есть ли в списке отрицательные числа
if otricatelnie == 0:
    # Вывод сообщения об отсутствии отрицательных значений
    print("Нету orpnuarenhshxx значений")
else:
    # Расчет процента отрицательных чисел от общего количества
    procent_otricatelnih = otricatelnie / 25 * 100

# Проверка: есть ли в списке положительные числа
if polozhitelnie == 0:
    # Вывод сообщения об отсутствии положительных значений
    print("Нету положительных значений")
else:
    # Расчет процента положительных чисел от общего количества
    procent_polozhitelnih = polozhitelnie / 25 * 100

# Проверка: есть ли в списке нулевые значения
if nulevie == 0:
    # Вывод сообщения об отсутствии нулевых значений
    print("Нету нулевых значений")
else:
    # Расчет процента нулевых значений от общего количества
    procent_mulevih = nulevie / 25 * 100

# Вывод итоговой статистики с количеством и процентами
print(f"Отрицательных {otricatelnie} {procent_otricatelnih}%, положительных {polozhitelnie} {procent_polozhitelnih}%, нулевых {nulevie} {procent_mulevih}%")
